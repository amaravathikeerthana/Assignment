-- ====================================================================
-- DBMS Module: CropSense Agriculture Advisory Database Schema
-- Compatible with SQLite and PostgreSQL
-- ====================================================================

-- 1. Farmers Table
CREATE TABLE IF NOT EXISTS farmers (
    farmer_id INTEGER PRIMARY KEY AUTOINCREMENT,
    full_name TEXT NOT NULL,
    phone_number TEXT NOT NULL UNIQUE,
    email TEXT,
    village_district TEXT NOT NULL,
    registered_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 2. Agricultural Fields Table
CREATE TABLE IF NOT EXISTS fields (
    field_id INTEGER PRIMARY KEY AUTOINCREMENT,
    farmer_id INTEGER NOT NULL,
    field_name TEXT NOT NULL,
    crop_type TEXT NOT NULL,
    soil_type TEXT NOT NULL,
    area_acres REAL NOT NULL CHECK(area_acres > 0),
    latitude REAL,
    longitude REAL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (farmer_id) REFERENCES farmers(farmer_id) ON DELETE CASCADE
);

-- 3. Sensor Readings Table (Time-Series Sensor Telemetry)
CREATE TABLE IF NOT EXISTS sensor_readings (
    reading_id INTEGER PRIMARY KEY AUTOINCREMENT,
    field_id INTEGER NOT NULL,
    temperature REAL NOT NULL,      -- in Celsius
    humidity REAL NOT NULL,         -- in Percentage (0-100)
    soil_moisture REAL NOT NULL,    -- in Percentage (0-100)
    rainfall REAL NOT NULL,         -- in mm
    is_valid BOOLEAN DEFAULT 1,     -- Data Engineering flag
    recorded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (field_id) REFERENCES fields(field_id) ON DELETE CASCADE
);

-- 4. Agricultural Advisories Table (Generated by ML & Decision Engine)
CREATE TABLE IF NOT EXISTS advisories (
    advisory_id INTEGER PRIMARY KEY AUTOINCREMENT,
    field_id INTEGER NOT NULL,
    predicted_yield REAL NOT NULL,   -- Quintals / Acre or Tonnes / Hectare
    drought_risk TEXT NOT NULL,      -- 'LOW', 'MEDIUM', 'HIGH'
    pest_risk TEXT NOT NULL,         -- 'LOW', 'MEDIUM', 'HIGH'
    recommended_action TEXT NOT NULL,
    issued_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (field_id) REFERENCES fields(field_id) ON DELETE CASCADE
);

-- Indexes for rapid time-series retrieval
CREATE INDEX IF NOT EXISTS idx_sensor_field_time ON sensor_readings(field_id, recorded_at);
CREATE INDEX IF NOT EXISTS idx_advisories_field_time ON advisories(field_id, issued_at);
